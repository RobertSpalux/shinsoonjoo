/** 생성물 전 채널(본진·네이버·블로그스팟·인스타 캡션·카드)에서 금지어 감지 — 매치된 단어 목록 반환 */
export function scanBannedTopics(article: Record<string, unknown>): string[] {
  const text = [
    article.main_website_markdown,
    article.naver_blog_content,
    article.blogspot_content,
    article.instagram_caption,
    JSON.stringify(article.carousel_json ?? ""),
  ]
    .map((v) => String(v ?? ""))
    .join("\n");
  return BANNED_TOPIC_TERMS.filter((t) => text.includes(t));
}

